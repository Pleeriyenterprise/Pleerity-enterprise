def _actions_required(report_type: str, ds: Optional[Dict[str, Any]]) -> bool:
    if report_type in ("score_explanation_pdf", "monthly_digest_pdf"):
        return False
    if report_type == "requirements_pdf":
        return False
    if report_type in (
        "audit_pack_overview",
        "audit_pack_audit_trail",
        "audit_pack_compliance_summary",
        "professional_audit_log",
    ):
        return False
    if not ds:
        return True
    reqs = ds.get("requirements") or []
    if not reqs:
        return False
    actionable = {"OVERDUE", "EXPIRED", "MISSING", "PENDING", "EXPIRING_SOON", "ACTION_REQUIRED"}
    for r in reqs:
        if str(r.get("status", "")).upper() in actionable:
            return True
        if str(r.get("client_lifecycle_state", "")).upper() in {"ACTION_REQUIRED", "PENDING_REVIEW"}:
            return True
    return report_type in ("formal_chronology", "evidence_readiness_portfolio", "evidence_readiness_property", "professional_audit_log")


def _assess_pdf(
    name: str,
    pdf: bytes,
    *,
    report_type: str,
    ds: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    text = _pdf_text(pdf)
    text = _strip_governance_footers(text)
    exec_text = _executive_portion(text)
    body_text = _executive_body(text)
    banner_text = _governance_banner(text)
    exec_lower = exec_text.lower()
    body_lower = body_text.lower()
    checks: Dict[str, Any] = {
        "renders_pdf": pdf.startswith(b"%PDF"),
        "byte_size": len(pdf),
        "sha256": _sha256(pdf),
        "page_count": max(1, len(__import__("pypdf").PdfReader(io.BytesIO(pdf)).pages)) if pdf.startswith(b"%PDF") else 0,
    }
    checks["executive_summary_early"] = (
        "executive summary" in exec_lower[:2500]
        or "executive summary" in text.lower()[:4000]
        or report_type in ("requirements_pdf", "score_explanation_pdf", "audit_pack_audit_trail")
    )
    action_markers = ("recommended next actions", "recommended remediation", "priority 1", "priority 2", "what to do next")
    checks["recommended_actions_present"] = any(k in text.lower() for k in action_markers) or report_type in (
        "score_explanation_pdf",
        "monthly_digest_pdf",
        "requirements_pdf",
        "audit_pack_overview",
        "audit_pack_audit_trail",
    )
    checks["recommended_actions_required"] = _actions_required(report_type, ds)
    checks["actionability_ok"] = checks["recommended_actions_present"] or not checks["recommended_actions_required"]
    checks["timeline_business_narrative"] = (
        "compliance chronology" in text.lower()
        or "operational activity chronology" in text.lower()
        or "electrical safety" in text.lower()
        or report_type not in ("formal_chronology", "evidence_readiness_portfolio", "professional_audit_log", "audit_pack_audit_trail")
    )
    checks["no_engineering_events_in_primary"] = not _ENGINEERING_EVENT_RE.search(exec_text)
    checks["governance_banner_leakage"] = bool(_LEAK_RE.search(banner_text))
    checks["no_technical_leakage_executive_body"] = not _LEAK_RE.search(body_text)
    checks["no_technical_leakage_executive"] = checks["no_technical_leakage_executive_body"]
    checks["technical_leakage_hits"] = list(dict.fromkeys(_LEAK_RE.findall(body_text)))[:10]
    checks["governance_leakage_hits"] = list(dict.fromkeys(_LEAK_RE.findall(banner_text)))[:10]
    checks["technical_appendix_when_audit"] = (
        "technical audit record" in text.lower()
        or "original action" in text.lower()
        or report_type in ("audit_pack_audit_trail",)
        or not ds_has_audit(report_type)
    )
    checks["no_microsecond_customer_timestamps"] = not _MICROSECOND_TS_RE.search(exec_text)
    checks["confidence_wording_present"] = any(
        k in body_lower
        for k in ("verified", "pending", "self-recorded", "awaiting", "historical", "confidence", "assurance")
    ) or report_type not in ("evidence_readiness_portfolio", "evidence_readiness_property", "formal_chronology")
    checks["automated_actor_not_bare_system"] = (
        "automated compliance monitoring" in text.lower()
        or "landlord" in text.lower()
        or "evidence verification" in text.lower()
        or not (ds and ds.get("audit_logs"))
        or report_type not in ("formal_chronology", "evidence_readiness_portfolio", "professional_audit_log", "audit_pack_audit_trail")
    )
    checks["professional_assessment"] = {
        "executive_readability": checks["executive_summary_early"],
        "business_narrative": checks["timeline_business_narrative"],
        "visual_structure_ok": checks["renders_pdf"] and checks["byte_size"] > 2000,
        "terminology_consistent": checks["no_engineering_events_in_primary"],
    }
    checks["pass"] = all(
        checks.get(k)
        for k in (
            "renders_pdf",
            "no_engineering_events_in_primary",
            "no_microsecond_customer_timestamps",
            "actionability_ok",
            "no_technical_leakage_executive_body",
        )
    )
    return {"report": name, "report_type": report_type, "checks": checks, "text_sample": text[:500]}


