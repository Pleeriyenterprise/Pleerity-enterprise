# Executive-section leakage patterns (must not appear before technical appendix)
_LEAK_RE = re.compile(
    r"\b("
    r"runtime-visible|projection=full|authority_version|generation boundary|"
    r"frozen deterministic snapshot|immutable artifact|manifest checksum|"
    r"report_presentation_v1|lifecycle_communication_v1|reconciliation_required|"
    r"regeneration completed|RISK_SIGNAL_REGEN|COMPLIANCE_RECALC_SLA"
    r")\b",
    re.I,
)
_ENGINEERING_EVENT_RE = re.compile(
    r"\b(Risk Signal Created|Compliance Score Updated|Compliance Score Drift Detected|"
    r"Risk assessment regeneration completed)\b",
    re.I,
)
_GOVERNANCE_FOOTER_RE = re.compile(
    r"Regulatory / evidential.*?(?=\n[A-Z]|\Z)|"
    r"This report is a frozen deterministic snapshot.*?(?=\n|\Z)|"
    r"Page \d+ \| Generated .*?(?=\n|\Z)|"
    r"Point-in-time export.*?(?=\n|\Z)|"
    r"Generated by Pleerity Enterprise Ltd.*?(?=\n|\Z)",
    re.I | re.S,
)


def _strip_governance_footers(text: str) -> str:
    return _GOVERNANCE_FOOTER_RE.sub("", text)


_MICROSECOND_TS_RE = re.compile(r"\d{4}-\d{2}-\d{2}\s+\d{2}:\d{2}:\d{2}\.\d{6}")


def _utc() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _pdf_text(pdf: bytes) -> str:
    from pypdf import PdfReader

    return "\n".join((p.extract_text() or "") for p in PdfReader(io.BytesIO(pdf)).pages)


def _executive_portion(text: str) -> str:
    marker = "Technical audit record"
    if marker in text:
        return text.split(marker, 1)[0]
    return text


def _executive_body(text: str) -> str:
    """Body content after governance banner — excludes regulatory disclaimer block."""
    body = _executive_portion(text)
    body_lower = body.lower()
    for anchor in (
        "executive summary",
        "compliance chronology",
        "evidence readiness report",
        "requirements report",
        "compliance score summary",
        "professional audit log",
        "audit trail",
        "compliance summary",
        "monthly operational",
        "audit evidence pack",
    ):
        idx = body_lower.find(anchor)
        if idx >= 0:
            return body[idx:]
    return body


def _governance_banner(text: str) -> str:
    body = _executive_portion(text)
    for anchor in (
        "Executive summary",
        "Compliance chronology",
        "Evidence Readiness Report",
        "Requirements Report",
    ):
        idx = body.find(anchor)
        if idx > 0:
            return body[:idx]
    return body[: min(len(body), 600)]


