/**
 * Injects build-time env for CRA (commit SHA + deployment tier).
 * Vercel provides VERCEL_GIT_COMMIT_SHA and VERCEL_ENV at build time.
 */
const fs = require('fs');
const path = require('path');

const sha =
  process.env.VERCEL_GIT_COMMIT_SHA ||
  process.env.GIT_COMMIT_SHA ||
  process.env.REACT_APP_BUILD_SHA ||
  'local-dev';

const deploymentEnv =
  process.env.VERCEL_ENV ||
  process.env.REACT_APP_DEPLOYMENT_ENV ||
  process.env.NODE_ENV ||
  'development';

const outPath = path.join(__dirname, '..', '.env.production.local');
const contents = [
  `# Generated by scripts/write-build-env.js — do not commit`,
  `REACT_APP_BUILD_SHA=${sha}`,
  `REACT_APP_DEPLOYMENT_ENV=${deploymentEnv}`,
  '',
].join('\n');

fs.writeFileSync(outPath, contents, 'utf8');
console.log(`[CVP] Wrote build env: sha=${sha.slice(0, 8)} env=${deploymentEnv}`);
